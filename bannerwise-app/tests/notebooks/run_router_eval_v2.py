tp = sum(1 for r in valid_results if r["expected_lane"] == "certified" and r["predicted_lane"] == "certified")
fp = sum(1 for r in valid_results if r["expected_lane"] == "analytical" and r["predicted_lane"] == "certified")
fn = sum(1 for r in valid_results if r["expected_lane"] == "certified" and r["predicted_lane"] == "analytical")
tn = sum(1 for r in valid_results if r["expected_lane"] == "analytical" and r["predicted_lane"] == "analytical")

precision = tp / (tp + fp) if (tp + fp) > 0 else 0.0
recall = tp / (tp + fn) if (tp + fn) > 0 else 0.0
