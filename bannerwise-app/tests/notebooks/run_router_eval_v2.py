    mlflow.log_param("eval_dataset_size", eval_count)
    mlflow.log_param("valid_results", total_valid)
    mlflow.log_param("vs_short_circuit_threshold", VS_SHORT_CIRCUIT_THRESHOLD)
    mlflow.log_param("judge_batch_size", JUDGE_BATCH_SIZE)
    mlflow.log_param("num_partitions", NUM_PARTITIONS)

    # Primary metrics
    mlflow.log_metric("gate_precision", precision)
    mlflow.log_metric("gate_recall", recall)
    mlflow.log_metric("f1_score", f1)
    mlflow.log_metric("staleness_enforcement", staleness_enforcement)
    mlflow.log_metric("accuracy", accuracy)

    # Secondary metrics
    mlflow.log_metric("near_miss_rejection_rate", near_miss_rejection_rate)
    mlflow.log_metric("adversarial_rejection_rate", adversarial_rejection_rate)
    mlflow.log_metric("retrieval_hit_rate", retrieval_hit_rate)
    mlflow.log_metric("mean_confidence_positives", mean_confidence_positives)
    mlflow.log_metric("mean_confidence_negatives", mean_confidence_negatives)
    mlflow.log_metric("latency_p95_ms", latency_p95)
    mlflow.log_metric("short_circuited_count", short_circuited_count)

    # Confusion matrix
    mlflow.log_metric("true_positives", tp)
    mlflow.log_metric("false_positives", fp)
    mlflow.log_metric("false_negatives", fn)
    mlflow.log_metric("true_negatives", tn)

    # Per-category accuracy
    for cat in set(r["category"] for r in valid_results):
        cat_results = [r for r in valid_results if r["category"] == cat]
        if cat_results:
            cat_accuracy = sum(1 for r in cat_results if r["is_correct"]) / len(cat_results)
            mlflow.log_metric(f"accuracy_{cat}", cat_accuracy)

    # Deployment gate pass/fail
    gate_passed = (precision >= 0.85 and recall >= 0.80)
    mlflow.log_metric("deployment_gate_passed", 1.0 if gate_passed else 0.0)

    # Performance metrics
    mlflow.log_metric("eval_duration_seconds", elapsed)
    mlflow.log_metric("throughput_rows_per_sec", result_count / elapsed if elapsed > 0 else 0)

    print(f"MLflow run logged: {run.info.run_id}")
    print(f"  Experiment: {EXPERIMENT_NAME}")
    print(f"  Deployment gate: {'PASSED' if gate_passed else 'FAILED'}")
    print(f"  Eval duration: {elapsed:.1f}s")

