import mlflow
from pyspark.sql import functions as F

# Collect results for metric computation
results = results_df.collect()
results_dicts = [row.asDict() for row in results]

# --- Primary Metrics ---
valid_results = [r for r in results_dicts if r["predicted_lane"] != "error"]
total_valid = len(valid_results)

tp = sum(1 for r in valid_results if r["expected_lane"] == "certified" and r["predicted_lane"] == "certified")
fp = sum(1 for r in valid_results if r["expected_lane"] == "analytical" and r["predicted_lane"] == "certified")
fn = sum(1 for r in valid_results if r["expected_lane"] == "certified" and r["predicted_lane"] == "analytical")
tn = sum(1 for r in valid_results if r["expected_lane"] == "analytical" and r["predicted_lane"] == "analytical")

precision = tp / (tp + fp) if (tp + fp) > 0 else 0.0
recall = tp / (tp + fn) if (tp + fn) > 0 else 0.0
f1 = 2 * precision * recall / (precision + recall) if (precision + recall) > 0 else 0.0
accuracy = (tp + tn) / total_valid if total_valid > 0 else 0.0

# Staleness enforcement
stale_results = [r for r in valid_results if r["category"] == "stale_entry_test"]
stale_correct = sum(1 for r in stale_results if r["predicted_lane"] == "analytical")
staleness_enforcement = stale_correct / len(stale_results) if stale_results else 1.0

# --- Secondary Metrics ---
positive_confidences = [r["predicted_confidence"] for r in valid_results if r["expected_lane"] == "certified"]
negative_confidences = [r["predicted_confidence"] for r in valid_results if r["expected_lane"] == "analytical"]

mean_confidence_positives = sum(positive_confidences) / len(positive_confidences) if positive_confidences else 0.0
mean_confidence_negatives = sum(negative_confidences) / len(negative_confidences) if negative_confidences else 0.0

near_miss_results = [r for r in valid_results if r["category"] == "near_miss_negative"]
near_miss_rejected = sum(1 for r in near_miss_results if r["predicted_lane"] == "analytical")
near_miss_rejection_rate = near_miss_rejected / len(near_miss_results) if near_miss_results else 1.0

adversarial_results = [r for r in valid_results if r["category"] == "adversarial"]
adversarial_rejected = sum(1 for r in adversarial_results if r["predicted_lane"] == "analytical")
adversarial_rejection_rate = adversarial_rejected / len(adversarial_results) if adversarial_results else 1.0

retrieval_results = [r for r in valid_results if r["expected_corpus_id"] is not None]
retrieval_hits = sum(1 for r in retrieval_results if r["predicted_corpus_id"] == r["expected_corpus_id"])
retrieval_hit_rate = retrieval_hits / len(retrieval_results) if retrieval_results else 0.0

latencies = sorted([r["latency_ms"] for r in valid_results])
latency_p95 = latencies[int(len(latencies) * 0.95)] if latencies else 0

# Short-circuit stats
short_circuited_count = sum(1 for r in valid_results if r["short_circuit"])
judge_calls_saved = short_circuited_count

