function useExample(el) {
    document.getElementById('promptInput').value = el.textContent;
}

async function submitPrompt() {
    const input = document.getElementById('promptInput');
    const prompt = input.value.trim();
    if (!prompt) return;

    const btn = document.getElementById('submitBtn');
    const loading = document.getElementById('loadingIndicator');
    const response = document.getElementById('responseSection');

    // Show loading state
    btn.disabled = true;
    loading.classList.remove('hidden');
    response.classList.add('hidden');

    try {
        const result = await apiPost('/api/quality/assess', { prompt });
        renderResponse(result);
    } catch (err) {
        renderError(err.message);
    } finally {
        btn.disabled = false;
        loading.classList.add('hidden');
    }
}

let _lastResult = null;
let _lastPrompt = null;

function renderResponse(result) {
    _lastResult = result;
    _lastPrompt = document.getElementById('promptInput').value;
    const section = document.getElementById('responseSection');
    const isCertified = result.lane === 'certified';

    section.innerHTML = `
        <div class="response-card">
            <div class="response-badge ${isCertified ? 'badge-certified' : 'badge-analytical'}">
                <span>${isCertified ? '\u2705' : '\u26A0\uFE0F'} ${result.badge}</span>
                <span class="confidence-display">Confidence: ${(result.confidence * 100).toFixed(1)}%</span>
            </div>
            <div class="response-body">
                <div class="response-answer">${formatAnswer(result.answer)}</div>
                ${!isCertified ? `
                    <div class="response-warning">
                        This answer was generated by Genie Agent and has not been certified by an SME.
                    </div>
                    <div class="response-actions">
                        <button class="btn btn-secondary" onclick="addToSMEReview()">Add to SME Review</button>
                        <button class="btn btn-secondary" onclick="flagIncorrect()">Flag Incorrect</button>
                    </div>
                ` : ''}
                <div class="provenance-section">
                    <button class="provenance-toggle" onclick="toggleProvenance(this)">
                        \u25B6 Show Provenance
                    </button>
                    <dl class="provenance-details hidden">
                        ${renderProvenance(result.provenance)}
                    </dl>
                </div>
            </div>
        </div>
    `;
    section.classList.remove('hidden');
}

function renderProvenance(provenance) {
    return Object.entries(provenance).map(([key, value]) => `
        <dt>${formatKey(key)}</dt>
        <dd>${typeof value === 'object' ? JSON.stringify(value) : value}</dd>
    `).join('');
}

function toggleProvenance(btn) {
    const details = btn.nextElementSibling;
    const isHidden = details.classList.toggle('hidden');
    btn.textContent = isHidden ? '\u25B6 Show Provenance' : '\u25BC Hide Provenance';
}

async function addToSMEReview() {
    if (!_lastResult || !_lastPrompt) {
        alert('No result to submit for review.');
        return;
    }
    try {
        const payload = {
            question: _lastPrompt,
            parameterized_sql: _lastResult.sql_executed || (_lastResult.provenance && _lastResult.provenance.sql_executed) || '',
            answer_template: _lastResult.answer || '',
            parameters: '[]',
            submitted_by: 'app_user',
            original_prompt: _lastPrompt,
        };
        await apiPost('/api/corpus/drafts', payload);
        alert('\u2705 Added to SME Review queue. Visit the Review page to certify or reject.');
    } catch (err) {
        alert('Failed to submit for review: ' + err.message);
    }
}

function flagIncorrect() {
    alert('Flagged as incorrect. An admin will review this response.');
}

function renderError(message) {
    const section = document.getElementById('responseSection');
    section.innerHTML = `<div class="response-warning">Error: ${escapeHtml(message)}</div>`;
    section.classList.remove('hidden');
}

